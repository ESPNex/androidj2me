#!/usr/bin/env python3
"""Rebuild the TEN AOSP 4.2.2_r1.2 boot JARs + framework-res.apk.

Requires ONLY the pinned frameworks/base and indispensable dependencies
acquired by bootstrap_framework42_only.py / bootstrap_android42_dependencies.py,
and the independently SHA-pinned host tools from bootstrap_aosp42_host_tools.py.
Uses the genuine AOSP Java/AIDL/.logtags/resources, AOSP ECJ/jarjar/aapt/aidl,
and dx compiled from pinned AOSP sources. All BIG files go under excluded
build/. Uses <=1 dx thread and a bounded heap for this ~2 GiB RAM host.

This is an out-of-tree, LOCAL Java/archive build, NOT an AOSP product build,
Android VM/zygote/JNI/Binder implementation, E63 test, or release. In
particular AOSP .logtags are regenerated by a small Python 3 generator.
Use --stage to validate/index/copy candidate JARs and write PIN HEADERS;
there is NEVER an automatic production SISX or Android-complete claim.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from tools.bootstrap_aosp42_host_tools import DEST as HOST, FILES as HOST_FILES, sha256
from tools.aosp42_eventlog_tags import generate as generate_logtags
from tools.pack_aosp42_jar_resources import pack as package_resources
from tools.stage_android42_runtime import FILES, inspect, stage

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "build/aosp-frameworks-base-4.2.2/repo"
DEPS = ROOT / "build/aosp42-runtime-dependencies"
OUT = ROOT / "build/aosp42-framework-build"
JDK = HOST / "jdk8/bin/java"
ECJ = HOST / "ecj-aosp42.jar"
DX = HOST / "dx.jar"
JAR = HOST / "jdk8/bin/jar"
JARJAR = HOST / "jarjar-aosp42.jar"
AAPT = HOST / "aapt"
AIDL = HOST / "aidl"
MODULES = ("core", "core-junit", "bouncycastle", "ext", "apache-xml",
           "framework", "telephony-common", "mms-common", "android.policy", "services")
BASE_DIRS = ("core/java", "graphics/java", "media/java",
             "media/mca/effect/java", "media/mca/filterfw/java",
             "media/mca/filterpacks/java", "location/java", "drm/java",
             "opengl/java", "sax/java", "wifi/java", "keystore/java",
             "icu4j/java", "voip/java", "telephony/java")


def validate_inputs() -> dict:
    from tools.bootstrap_framework42_only import COMMIT as BASE_COMMIT
    from tools.bootstrap_android42_dependencies import PROJECTS
    repositories = {"frameworks/base": (BASE, BASE_COMMIT)}
    repositories.update({name: (DEPS / name, expected[2])
                         for name, expected in PROJECTS.items()})
    for name, (folder, commit) in repositories.items():
        if not (folder / ".git").is_dir():
            raise FileNotFoundError(f"AOSP checkout absent: {folder}")
        head = subprocess.check_output(["git", "-C", str(folder),
                                        "rev-parse", "HEAD"], text=True).strip()
        dirty = subprocess.check_output(["git", "-C", str(folder),
                                         "status", "--porcelain"], text=True).strip()
        if head != commit or dirty:
            raise ValueError(f"{name}: wrong commit or modified tracked checkout")
    for name, (_, expected, _) in HOST_FILES.items():
        path = HOST / name
        if not path.is_file() or sha256(path) != expected:
            raise ValueError(f"missing or modified SHA-pinned host tool {path}")
    if not DX.is_file() or not JDK.is_file() or not (BASE / "preloaded-classes").is_file():
        raise FileNotFoundError("dx, JDK8 or AOSP preloaded-classes missing")
    for binary in (AAPT, AIDL):
        # This also catches missing Linux i386 runtime libraries early.
        result = subprocess.run([str(binary)], text=True, capture_output=True)
        if "usage:" not in result.stderr and "Usage:" not in result.stderr + result.stdout:
            raise RuntimeError(f"{binary} unavailable: {result.stderr.strip()[:300]}")
    return {name: commit for name, (_, commit) in repositories.items()}


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def java_files(folder: Path) -> list[Path]:
    return sorted(folder.rglob("*.java")) if folder.is_dir() else []


def run(command: list[str], log: Path) -> None:
    log.parent.mkdir(parents=True, exist_ok=True)
    with log.open("w") as stream:
        result = subprocess.run(command, cwd=ROOT, stdout=stream,
                                stderr=subprocess.STDOUT, text=True)
    if result.returncode:
        lines = log.read_text(errors="replace").splitlines()
        raise RuntimeError(f"{command[0]} failed ({result.returncode}):\n" +
                           "\n".join(lines[-90:]))


def write_sources(module: str, files: list[Path]) -> Path:
    if not files or len(files) != len(set(files)) or not all(p.is_file() for p in files):
        raise ValueError(f"missing/duplicate AOSP source for {module}")
    out = OUT / module / "sources.list"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(rel(p) for p in files) + "\n")
    return out


def classes(module: str) -> Path:
    return OUT / ("core-classes" if module == "core" else module + "/classes")


def ecj(module: str, files: list[Path], *, classpath: tuple[str, ...] = (),
        level: str = "-6", heap: int = 1200) -> None:
    output = classes(module)
    output.mkdir(parents=True, exist_ok=True)
    sources = write_sources(module, files)
    command = [str(JDK), f"-Xmx{heap}m", "-XX:+UseSerialGC", "-jar", str(ECJ),
               level, "-nowarn", "-maxProblems", "80", "-encoding", "UTF-8"]
    if module != "core":
        command += ["-bootclasspath", rel(classes("core"))]
    if classpath:
        command += ["-classpath", ":".join(classpath)]
    command += ["-d", rel(output), "@" + rel(sources)]
    run(command, OUT / module / "ecj.log")
    count = len(list(output.rglob("*.class")))
    if not count:
        raise ValueError(f"{module}: no compiled AOSP classes")
    print(f"{module}: compiled {count} Java classes", flush=True)


def dx(module: str, jarjar_file: Path | None = None) -> None:
    dest = OUT / f"{module}.jar"
    source = jarjar_file or classes(module)
    run([str(JDK), "-Xmx1250m", "-XX:+UseSerialGC", "-cp", str(DX),
         "com.android.dx.command.Main", "--dex", "--core-library",
         "--num-threads=1", "--output=" + rel(dest), rel(source)],
        OUT / module / "dx.log")
    if module in ("core", "ext", "apache-xml", "framework"):
        print(f"{module}: {package_resources(module)} genuine AOSP Java resources")
    print(f"{module}: {dest.stat().st_size} bytes of DEX JAR", flush=True)


def build_core() -> None:
    root = DEPS / "libcore"
    files = [p for part in ("dalvik", "dom", "json", "luni", "support", "xml")
             for p in java_files(root / part / "src/main/java")]
    ecj("core", files, heap=1450)
    dx("core")


def build_junit() -> None:
    root = DEPS / "junit"
    common = (root / "Common.mk").read_text()
    segment = common.split("core-junit-files :=", 1)[1].split(
        "# List of source to build into", 1)[0]
    listed = re.findall(r"src/junit/framework/[\w]+\.java", segment)
    if len(listed) != 11:
        raise ValueError("AOSP core-junit-files changed")
    files = java_files(root / "src/junit/extensions") + [root / p for p in listed]
    ecj("core-junit", files, classpath=(rel(classes("core")),))
    dx("core-junit")


def build_bouncycastle() -> None:
    root = DEPS / "bouncycastle"
    files = [p for p in java_files(root / "bcprov/src/main/java")
             if p.name != "AndroidDigestFactoryBouncyCastle.java"]
    ecj("bouncycastle", files, classpath=(rel(classes("core")),),
        level="-5", heap=1250)  # AOSP jarjar-1.0rc8 rejects ECJ 1.6 stack frames.
    intermediates = OUT / "bouncycastle"
    first = intermediates / "classes-pre-jarjar.jar"
    second = intermediates / "classes-jarjar.jar"
    run([str(JAR), "cf", rel(first), "-C", rel(classes("bouncycastle")), "."],
        intermediates / "jar.log")
    run([str(JDK), "-Xmx600m", "-cp", str(JARJAR),
         "com.tonicsystems.jarjar.Main", "process", rel(root / "jarjar-rules.txt"),
         rel(first), rel(second)], intermediates / "jarjar.log")
    dx("bouncycastle", second)


def build_ext() -> None:
    files = [p for part in ("nist-sip/java", "apache-http/src", "tagsoup/src",
                             "libphonenumber/java/src")
             for p in java_files(DEPS / part)]
    ecj("ext", files, classpath=(rel(classes("core")),), heap=1350)
    dx("ext")


def build_apache() -> None:
    files = java_files(DEPS / "apache-xml/src/main/java")
    ecj("apache-xml", files, classpath=(rel(classes("core")),))
    dx("apache-xml")


def compile_resources() -> None:
    out = OUT / "framework-res"
    generated = out / "generated"
    generated.mkdir(parents=True, exist_ok=True)
    inputs = BASE / "core/res"
    # BUILD_PACKAGE normally also passes -A for framework-res/assets.
    run([str(AAPT), "package", "-x", "-f", "-m", "-M",
         rel(inputs / "AndroidManifest.xml"), "-S", rel(inputs / "res"),
         "-A", rel(inputs / "assets"), "-J", rel(generated),
         "-F", rel(OUT / "framework-res.apk")], out / "aapt.log")
    for p in (generated / "android/R.java", generated / "android/Manifest.java",
              generated / "com/android/internal/R.java"):
        if not p.is_file():
            raise ValueError(f"aapt omitted {p}")
    print("framework-res.apk: compiled AOSP resources and assets", flush=True)


def aidl_for_framework() -> list[Path]:
    output = OUT / "framework/aidl-generated"
    output.mkdir(parents=True, exist_ok=True)
    roots = [BASE / p for p in BASE_DIRS] + [DEPS / "telephony-common/src/java"]
    opts = ["-I" + rel(p) for p in roots]
    generated: list[Path] = []
    # Only production framework source trees selected by Android.mk. A full
    # frameworks/base checkout also contains core/tests IAidlTest.aidl, which
    # imports test-only android.os.AidlTest and is NOT a bootclasspath API.
    # Scanning BASE.rglob() would accidentally compile those test interfaces.
    sources = sorted({p for part in BASE_DIRS
                      for p in (BASE / part).rglob("*.aidl")})
    for source in sources:
        data = source.read_text(errors="replace")
        if not re.search(r"\binterface\s+[A-Za-z_]\w*\s*\{", data):
            continue  # AOSP parcelable declarations are resolved by aidl -I.
        # Stale 4.2 source imports a nonexistent TextBoxAttribute. Not part
        # of Android.mk's selected framework AIDL list and has no Java calls.
        if source.name == "IInputConnectionCallback.aidl":
            print("skipped stale AOSP IInputConnectionCallback.aidl import", flush=True)
            continue
        match = re.search(r"\bpackage\s+([\w.]+)\s*;", data)
        if not match:
            raise ValueError(f"missing AIDL package: {source}")
        target = output.joinpath(*match.group(1).split("."), source.stem + ".java")
        run([str(AIDL), *opts, "-o" + rel(output), rel(source)],
            OUT / "framework/aidl-latest.log")
        if not target.is_file():
            raise ValueError(f"aidl failed to generate {target}")
        generated.append(target)
    if len(generated) != 166:
        raise ValueError(f"unexpected framework AIDL interfaces {len(generated)}")
    return generated


def logs(module: str, sources: list[Path]) -> list[Path]:
    output = OUT / module / "eventlog-generated"
    files = []
    for source in sources:
        match = re.search(r"\boption java_package ([\w.]+)",
                          source.read_text())
        if not match:
            raise ValueError(f"eventlog package missing from {source}")
        path = output.joinpath(*match.group(1).split("."), "EventLogTags.java")
        generate_logtags(source, path)
        files.append(path)
    return files


def build_framework() -> None:
    compile_resources()
    aids = aidl_for_framework()
    tags = logs("framework", [BASE / p for p in (
        "core/java/android/content/EventLogTags.logtags",
        "core/java/android/speech/tts/EventLogTags.logtags",
        "core/java/android/webkit/EventLogTags.logtags")])
    generated = OUT / "framework-res/generated"
    files = ([p for folder in BASE_DIRS for p in java_files(BASE / folder)] +
             aids + java_files(generated) + tags)
    cp = (rel(classes("core-junit")), rel(classes("ext")),
          rel(OUT / "bouncycastle/classes-jarjar.jar"),
          rel(classes("apache-xml")))
    ecj("framework", files, classpath=cp, heap=1450)
    dx("framework")


def build_telephony() -> None:
    module = "telephony-common"
    source = DEPS / "telephony-common/src/java"
    aids: list[Path] = []
    output = OUT / module / "aidl-generated"
    output.mkdir(parents=True, exist_ok=True)
    for name in ("IIccPhoneBook", "ISms"):
        path = source / f"com/android/internal/telephony/{name}.aidl"
        run([str(AIDL), "-I" + rel(source), *["-I" + rel(BASE / p)
                                             for p in BASE_DIRS],
             "-o" + rel(output), rel(path)], OUT / module / "aidl-latest.log")
        result = output / "com/android/internal/telephony" / (name + ".java")
        if not result.is_file():
            raise ValueError(f"telephony aidl output missing: {name}")
        aids.append(result)
    tags = logs(module, [source / "com/android/internal/telephony/EventLogTags.logtags"])
    ecj(module, java_files(source) + aids + tags,
        classpath=(rel(classes("framework")), rel(classes("ext")),
                   rel(OUT / "bouncycastle/classes-jarjar.jar")), heap=1350)
    dx(module)


def build_mms() -> None:
    ecj("mms-common", java_files(DEPS / "mms-common/src/java"),
        classpath=(rel(classes("framework")),rel(classes("telephony-common")),
                   rel(classes("ext"))))
    dx("mms-common")


def build_policy() -> None:
    ecj("android.policy", java_files(BASE / "policy/src"),
        classpath=(rel(classes("framework")),rel(classes("ext")),
                   rel(classes("telephony-common"))))
    dx("android.policy")


def build_services() -> None:
    source = BASE / "services/java"
    tags = logs("services", [source / "com/android/server/EventLogTags.logtags",
                             source / "com/android/server/am/EventLogTags.logtags"])
    ecj("services", java_files(source) + tags,
        classpath=tuple(rel(classes(p)) for p in (
            "framework", "ext", "telephony-common", "mms-common",
            "android.policy", "apache-xml")) +
        (rel(OUT / "bouncycastle/classes-jarjar.jar"),), heap=1550)
    dx("services")


def build(*, stage_files: bool) -> None:
    commits = validate_inputs()
    OUT.mkdir(parents=True, exist_ok=True)
    for task in (build_core, build_junit, build_bouncycastle, build_ext,
                 build_apache, build_framework, build_telephony, build_mms,
                 build_policy, build_services):
        print(f"building {task.__name__}...", flush=True)
        task()
    manifest = {"tag": "android-4.2.2_r1.2", "source_commits": commits,
                "host_tools_sha256": {name: sha256(HOST / name)
                                      for name in HOST_FILES},
                "boot_jar_order": [n for n, _, kind in FILES if kind == 2],
                "out_of_tree_build": True, "android_runtime_ready": False,
                "artifacts": {n: {"bytes": inspect(OUT / n, needed)[0],
                                  "sha256": sha256(OUT / n)}
                              for n, needed, _ in FILES}}
    (OUT / "local-build-provenance.json").write_text(json.dumps(manifest, indent=2) + "\n")
    if stage_files:
        record = stage(OUT)
        print(f"staged {len(record['files'])} candidate archives, "
              f"{record['bootclasspath_unique_classes']} indexed classes")
    else:
        print("Local AOSP DEX JARs compiled; run with --stage for candidate pins")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stage", action="store_true",
                        help="also validate/index/copy & pin candidates, not a SISX")
    args = parser.parse_args()
    build(stage_files=args.stage)
