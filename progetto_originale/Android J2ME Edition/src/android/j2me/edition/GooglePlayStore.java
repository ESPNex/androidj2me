    private void search_buttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_search_buttonActionPerformed
        
        if (store_search_field.getText().equalsIgnoreCase("file manager") || store_search_field.getText().equalsIgnoreCase("file") ||  store_search_field.getText().equalsIgnoreCase("file man"))
        {
            app_page_screen.setVisible(false);
            no_results_found_screen.setVisible(false);
            store_home.setVisible(true);
            apps_section_text.setText("1 result found.");
           
        }
        
        else
        {
            app_page_screen.setVisible(false);
            store_home.setVisible(false);
            no_results_found_screen.setVisible(true);
        }
    }//GEN-LAST:event_search_buttonActionPerformed

    private void action_buttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_action_buttonActionPerformed

        action_button.setVisible(false);
        HomeScreen h = new HomeScreen();
        installing_progressbar.setVisible(true);
        downloading_percent.setVisible(true);
        downloading_text.setVisible(true);
        FileManager manager = new FileManager ();
        SwingWorker<Void, Integer> worker = new SwingWorker<Void, Integer>() {
    @Override
    protected Void doInBackground() throws Exception {
        for (int i = 0; i <= 100; i++) {
            publish(i);
            try {
                Thread.sleep(150);
            } catch (InterruptedException ex) {
                Logger.getLogger(GooglePlayStore.class.getName()).log(Level.SEVERE, null, ex);
            }
            
        }
        return null;
    }

    @Override
    protected void process(List<Integer> chunks) {
        int i = chunks.get(chunks.size() - 1);
        installing_progressbar.setValue(i);
        String num = Integer.toString(i);
        downloading_percent.setText(num + "%");
        if (installing_progressbar.getValue() == 100)
            {
            try {
                Thread.sleep(2000);
            } catch (InterruptedException ex) {
                Logger.getLogger(GooglePlayStore.class.getName()).log(Level.SEVERE, null, ex);
            }
                installing_progressbar.setVisible(false);
                downloading_percent.setVisible(false);
                downloading_text.setText("Installing...");
                installed = true;
            }
    }

    @Override
    protected void done() {
        try {
            Thread.sleep(5000);
        } catch (InterruptedException ex) {
            Logger.getLogger(GooglePlayStore.class.getName()).log(Level.SEVERE, null, ex);
        }
        downloading_text.setVisible(false);
        action_button.setText("OPEN");
        action_button.setVisible(true);
        h.filemanager_hotspot.setVisible(true);
        h.filemanager_icon.setVisible(true);
        h.filemanager_text.setVisible(true);
        
        
    }
};

worker.execute();



        
    }//GEN-LAST:event_action_buttonActionPerformed

