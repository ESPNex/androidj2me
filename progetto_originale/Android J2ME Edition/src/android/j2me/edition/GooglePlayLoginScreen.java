    private void next_buttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_next_buttonActionPerformed
        if (email_field.getText().equals("") && password_field.getText().equals("")){
            
            email_line.setVisible(false);
            email_error_line.setVisible(true);
            email_error_text.setVisible(true);
            email_error_text.setText("Google account email required.");
            password_line.setVisible(false);
            password_error_line.setVisible(true);
            password_error_text.setVisible(true);
            password_error_text.setText("Google account password required.");
        }

        
      else if (email_field.getText().contains("@gmail.com") && password_field.getText().length() >= 8 && password_field.getText().matches(".*[a-z].*") || password_field.getText().matches(".*[A-Z].*") && password_field.getText().matches(".*[0-9].*") && password_field.getText().matches(".*[\\p{Punct}].*"))
        {
            email_line.setVisible(true);
            email_error_line.setVisible(false);
            email_error_text.setVisible(false);
            password_line.setVisible(true);
            password_error_line.setVisible(false);
            password_error_text.setVisible(false);
            String email = email_field.getText(); 
            GooglePlayStore store = new GooglePlayStore();
            setVisible(false);
            store.setVisible(true);
            store.setSize(461, 400);
            char letter = email.charAt(0);
            String name = Character.toString(letter);
            store.account_letter.setText(name);
            store.no_results_found_screen.setVisible(false);
            store.app_page_screen.setVisible(false);
            store.store_home.setVisible(true);
            loggedIn = true;
            
            
            
        }
        
        else
        {
            email_line.setVisible(false);
            email_error_line.setVisible(true);
            email_error_text.setVisible(true);
            email_error_text.setText("Invalid email address.");
            password_line.setVisible(false);
            password_error_line.setVisible(true);
            password_error_text.setVisible(true);
            password_error_text.setText("Password should contain at least 8 characters, a number and a letter.");
            
            
            
            
        }
        
        
                

    }//GEN-LAST:event_next_buttonActionPerformed

