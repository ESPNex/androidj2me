    private void settings_hotspotActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_settings_hotspotActionPerformed
       Settings s = new Settings();
       HomeScreen h = new HomeScreen ();
       SimpleDateFormat formatter = new SimpleDateFormat ("HH:mm");
        Date date = new Date ();
        s.time.setText(formatter.format(date));
       s.batterybar.setValue(batterybar.getValue());
        setVisible (false);
        s.setSize(462, 386);
        s.setVisible(true);
        s.wifi_hotspot_on.setVisible(false);
        s.wifi_button.setBackground(Color.getHSBColor(204/360.0f, 7/100.0f, 25/100.0f));
        s.wifi_text.setText("OFF");
        
        if (s.wifi_button.getBackground() == Color.getHSBColor(204/360.0f, 7/100.0f, 25/100.0f) && s.wifi_text.getText().equals("OFF"))
        {
           s.wifi_button.setBackground(Color.getHSBColor(204/360.0f, 7/100.0f, 25/100.0f));
           s.wifi_text.setText("OFF");
        }
        else if (s.wifi_button.getBackground() == Color.getHSBColor(210/360.0f, 80/100.0f, 100/100.0f) && s.wifi_text.getText().equals("ON"))
        {
           s.wifi_button.setBackground(Color.getHSBColor(210/360.0f, 80/100.0f, 100/100.0f));
           s.wifi_text.setText("ON"); 
        }
        if (wifi_statusbar_icon.isVisible() == true)
        {
           s.wifi_statusbar_icon.setVisible(true);
           s.wifi_button.setBackground(Color.getHSBColor(210/360.0f, 80/100.0f, 100/100.0f));
           s.wifi_text.setText("ON"); 
           
        }
        else
        {
          s.wifi_statusbar_icon.setVisible(false);
          s.wifi_button.setBackground(Color.getHSBColor(204/360.0f, 7/100.0f, 25/100.0f));
          s.wifi_text.setText("OFF");
        }
        
        
    }//GEN-LAST:event_settings_hotspotActionPerformed

