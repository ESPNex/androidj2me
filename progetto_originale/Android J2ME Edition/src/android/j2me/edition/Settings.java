    private void navbar_home_buttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_navbar_home_buttonActionPerformed
        HomeScreen h = new HomeScreen ();
        h.filemanager_hotspot.setVisible(false);
        h.filemanager_icon.setVisible(false);
        h.filemanager_text.setVisible(false);
        setVisible (false);
        h.setSize(400,370);
        h.setVisible(true);
        h.ShutdownScreen.setVisible(false);
        h.BatteryLowAlertScreen.setVisible(false);
        if (wifi_statusbar_icon.isVisible() == true)
        {
           h.wifi_statusbar_icon.setVisible(true);
        }
        else
        {
          h.wifi_statusbar_icon.setVisible(false); 
        }
        if (GooglePlayStore.installed == true)
        {
           h.filemanager_hotspot.setVisible(true);
           h.filemanager_icon.setVisible(true);
           h.filemanager_text.setVisible(true);
            
        }
        SimpleDateFormat formatter = new SimpleDateFormat ("HH:mm");
        Date date = new Date ();
        time.setText(formatter.format(date));
        h.time.setText(formatter.format(date));
        
        
    }//GEN-LAST:event_navbar_home_buttonActionPerformed

