    private void lowbattery_audio_hotspotActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_lowbattery_audio_hotspotActionPerformed
         // Specify the path of the audio file
            File audioFile = new File("C:\\Users\\Utente\\Documents\\NetBeansProjects\\Android J2ME Edition\\src\\android\\j2me\\edition\\lowbattery.wav");

            // Create an AudioInputStream from the audio file
            AudioInputStream audioStream = null;
        try {
            audioStream = AudioSystem.getAudioInputStream(audioFile);
        } catch (UnsupportedAudioFileException ex) {
            Logger.getLogger(FileManager.class.getName()).log(Level.SEVERE, null, ex);
        } catch (IOException ex) {
            Logger.getLogger(FileManager.class.getName()).log(Level.SEVERE, null, ex);
        }

            // Get a clip resource
            Clip lowbatterysound = null;
        try {
            lowbatterysound = AudioSystem.getClip();
        } catch (LineUnavailableException ex) {
            Logger.getLogger(FileManager.class.getName()).log(Level.SEVERE, null, ex);
        }

        try {
            // Open audio clip and load samples from the audio input stream
            lowbatterysound.open(audioStream);
        } catch (LineUnavailableException ex) {
            Logger.getLogger(FileManager.class.getName()).log(Level.SEVERE, null, ex);
        } catch (IOException ex) {
            Logger.getLogger(FileManager.class.getName()).log(Level.SEVERE, null, ex);
        }
            
            // Start playing the audio
            lowbatterysound.start();
            audio_playing.setText("lowbattery.wav playing...");
            audio_playing.setVisible(true);
            
 
    }//GEN-LAST:event_lowbattery_audio_hotspotActionPerformed

